/**
 * 获取高校名称的所有可能候选变体 (包含标准全称、原输入)
 */
export function getFormalUniversityVariants(inputName: string): string[] {
  if (!inputName) return [];
  const clean = inputName.trim();
  const variants = new Set<string>();
  variants.add(clean);

  // 1. 查简称映射表
  if (UNIVERSITY_ALIAS_MAP[clean]) {
    UNIVERSITY_ALIAS_MAP[clean].forEach(v => variants.add(v));
  }

  // 2. 尝试子串匹配
  for (const [alias, formals] of Object.entries(UNIVERSITY_ALIAS_MAP)) {
    if (clean.includes(alias) || alias.includes(clean)) {
      formals.forEach(f => variants.add(f));
    }
  }

  // 3. 剥离“分校”、“校区”后缀
  const withoutCampus = clean.replace(/(\(|（).*(校区|分校)(\)|）)$/, '').trim();
  if (withoutCampus && withoutCampus !== clean) {
    variants.add(withoutCampus);
  }

  return Array.from(variants);
}

/**
 * 获取专业名称的所有可能候选变体
 */
export function getFormalMajorVariants(inputName: string): string[] {
  if (!inputName) return [];
  const clean = inputName.trim();
  const variants = new Set<string>();
  variants.add(clean);

  if (MAJOR_ALIAS_MAP[clean]) {
    MAJOR_ALIAS_MAP[clean].forEach(v => variants.add(v));
  }

  for (const [alias, formals] of Object.entries(MAJOR_ALIAS_MAP)) {
    if (clean.includes(alias) || alias.includes(clean)) {
      formals.forEach(f => variants.add(f));
    }
  }

  return Array.from(variants);
}
